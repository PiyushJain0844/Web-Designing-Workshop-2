// Arithmetic Operators

let a = 5;
let b = 10;

// Addition
console.log("a + b = ", a + b);     // a + b =  15

// Subtraction
console.log("a - b = ", a - b);     // a - b =  -5

// Multiplication
console.log("a * b = ", a * b);     // a * b =  50

// Division
console.log("a / b = ", a / b);     // a / b =  0.5

// Modulus
console.log("a % b = ", a % b);     // a % b =  5

// Exponentiation
console.log("a ** b = ", a ** b);     // a ** b =  9765625


// Unary Operators

// Increment
console.log("a++ = ", a++);     // a++ =  5
console.log("a = ", a);         // a = 6
// Decrement

console.log("b-- = ", b--);     // b-- =  10
console.log("b = ", b);         // b = 9