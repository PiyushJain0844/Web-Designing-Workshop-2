// Assignment Operator

let a = 5;
let b = 2;

console.log("a += 4 = ", a += 4);    // a += 4 =  9
console.log("a -= 4 = ", a -= 4);    // a -= 4 = 1
console.log("a *= 4 = ", a *= 4);    // a *= 4 =  20
console.log("a /= 4 = ", a /= 4);    // a /= 4 =  1.25
console.log("a %= 4 = ", a %= 4);    // a %= 4 =  1
console.log("a **= 4 = ", a **= 4);    // a **= 4 =  625