// Logical Operator

let a = 6;
let b = 5;

let cond1 = a > b;  // true
let cond2 = a === b;  // true

// Logical AND
console.log("cond1 && cond2 = ", cond1 && cond2);    // cond1 && cond2 =  false

// Logical OR
console.log("cond1 || cond2 = ", cond1 || cond2);    // cond1 || cond2 =  true

// Logical NOT
console.log("!cond1 = ", !cond1);    // !cond1 =  false
console.log("!cond2 = ", !cond2);    // !cond2 =  true